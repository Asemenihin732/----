import type { Card, CardCategory, RoundNumber, TeamId, Variant } from '../game/types'

let counter = 0
const nextId = (team: string) => `${team}-${++counter}`

function v(
  key: 'A' | 'B' | 'C',
  label: string,
  xlanceAction: string,
  opts: Partial<Omit<Variant, 'key' | 'label' | 'xlanceAction'>> = {},
): Variant {
  return { key, label, xlanceAction, ...opts }
}

function card(
  team: TeamId | 'universal',
  round: RoundNumber | null,
  category: CardCategory,
  title: string,
  flavor: string,
  variants: Variant[],
): Card {
  return { id: nextId(team), team, round, category, title, flavor, variants }
}

